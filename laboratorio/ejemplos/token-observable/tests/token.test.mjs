import test from 'node:test'
import assert from 'node:assert/strict'
import {readFile} from 'node:fs/promises'
import {JsonRpcProvider, MaxUint256} from 'ethers'
import {TokenSession, amount} from '../ui/operaciones.mjs'
const provider = new JsonRpcProvider(process.env.LAB_RPC_URL, undefined, {cacheTimeout: -1, batchMaxCount: 1})
const artifact = JSON.parse(await readFile('artifacts/contracts/TokenAula.sol/TokenAula.json', 'utf8'))
const instance = async (creator = 0, receiver = 0) => {const s=new TokenSession(provider,artifact);await s.connect();await s.create(creator,receiver);return s}
test.after(() => provider.destroy())
const tokens = state => ({supply: state.totalSupplyUnits, balances: state.accounts.map(a=>a.aulaUnits), allowances:state.allowances})

test('Token observable: emisión única, creador distinto del receptor y evento de creación', async () => {
  const s=await instance(1,0), state=await s.snapshot(), record=s.records[0]
  assert.equal(state.totalSupplyUnits, amount('1000000').toString())
  assert.equal(state.accounts[0].aulaUnits, amount('1000000').toString())
  assert.equal(state.accounts[1].aulaUnits, '0')
  assert.equal(record.from, s.addresses[1])
  assert.equal(record.events[0].name,'Transfer')
  assert.equal(record.events[0].arguments[0],'0x0000000000000000000000000000000000000000')
  assert.equal(record.events[0].arguments[1],s.addresses[0])
  assert.equal(record.events[0].arguments[2],amount('1000000').toString())
  const methods=artifact.abi.filter(x=>x.type==='function').map(x=>x.name)
  for(const name of ['mint','burn','owner','pause'])assert.equal(methods.includes(name),false)
})
test('Token observable: unidades exactas, fracción mínima y rechazo de precisión excesiva', async () => {
  assert.equal(amount('0,5'),500000000000000000n)
  assert.equal(amount('0.000000000000000001'),1n)
  assert.throws(()=>amount('0.0000000000000000001'))
  assert.throws(()=>amount('1.000,5'))
  const s=await instance();await s.transfer(0,1,'0.000000000000000001')
  const state=await s.snapshot()
  assert.equal(state.accounts[1].aulaUnits,'1')
  assert.equal(state.accounts[0].aulaUnits,(amount('1000000')-1n).toString())
})
test('Token observable: approve conserva saldos, transferFrom tiene un destinatario diferente del spender', async () => {
  const s=await instance();await s.transfer(0,1,'10')
  const before=await s.snapshot();await s.approve(0,1,'3');const approved=await s.snapshot()
  assert.deepEqual(approved.accounts.map(x=>x.aulaUnits),before.accounts.map(x=>x.aulaUnits))
  const used=await s.transferFrom(1,0,2,'2'), state=used.after
  assert.equal(state.accounts[0].aulaUnits,amount('999988').toString())
  assert.equal(state.accounts[1].aulaUnits,amount('10').toString())
  assert.equal(state.accounts[2].aulaUnits,amount('2').toString())
  assert.equal(state.allowances[0][1],amount('1').toString())
  assert.equal(used.from,s.addresses[1])
  assert.equal(used.events[0].name,'Transfer')
  assert.deepEqual(used.events[0].arguments,[s.addresses[0],s.addresses[2],amount('2').toString()])
  assert.equal(used.events.some(e=>e.name==='Approval'),false)
  assert.equal(state.accounts.reduce((sum,x)=>sum+BigInt(x.aulaUnits),0n),amount('1000000'))
})
test('Token observable: approve sustituye el permiso y revocar impide un uso posterior', async () => {
  const s=await instance();await s.approve(0,1,'3');await s.approve(0,1,'2')
  assert.equal((await s.snapshot()).allowances[0][1],amount('2').toString())
  await s.approve(0,1,'0')
  const result=await s.simulate(1,0,2,'1')
  assert.equal(result.accepted,false)
  assert.equal(result.after.allowances[0][1],'0')
})
test('Token observable: estimar un rechazo no publica operación ni consume gas o nonce', async () => {
  const s=await instance();await s.approve(0,1,'1')
  const result=await s.simulate(1,0,2,'2')
  assert.equal(result.accepted,false)
  assert.match(result.message,/permiso/)
  assert.equal(result.hash,null)
  assert.equal(result.before.block,result.after.block)
  assert.deepEqual(result.before.accounts,result.after.accounts)
  assert.deepEqual(tokens(result.before),tokens(result.after))
})
test('Token observable: reversión incluida conserva tokens, cobra ETH al spender y consume nonce', async () => {
  const s=await instance();await s.approve(0,1,'1')
  const record=await s.transferFrom(1,0,2,'2',true)
  assert.equal(record.status,0)
  assert.deepEqual(tokens(record.before),tokens(record.after))
  assert.ok(BigInt(record.gasUsed)>0n)
  assert.ok(BigInt(record.feeWei)>0n)
  assert.equal(BigInt(record.before.accounts[1].ethWei)-BigInt(record.after.accounts[1].ethWei),BigInt(record.feeWei))
  assert.equal(record.after.accounts[1].nonce,record.before.accounts[1].nonce+1)
  assert.equal(record.after.accounts[0].ethWei,record.before.accounts[0].ethWei)
  assert.equal(BigInt(record.feeWei),BigInt(record.burnedWei)+BigInt(record.tipWei))
  assert.deepEqual(record.events,[])
})
test('Token observable: el permiso pertenece al par owner-spender y también hace falta saldo', async () => {
  const s=await instance();await s.approve(0,1,'3')
  assert.equal((await s.simulate(2,0,2,'1')).accepted,false)
  await s.transfer(0,1,'999999')
  const result=await s.transferFrom(1,0,2,'2',true)
  assert.equal(result.status,0)
  assert.equal(result.after.allowances[0][1],amount('3').toString())
  assert.deepEqual(tokens(result.before),tokens(result.after))
})
test('Token observable: la aprobación máxima de OpenZeppelin 5.4 no disminuye al usarla', async () => {
  const s=await instance()
  await(await s.contract.connect(s.signers[0]).approve(s.addresses[1],MaxUint256)).wait()
  await s.transferFrom(1,0,2,'2')
  assert.equal((await s.snapshot()).allowances[0][1],MaxUint256.toString())
})
